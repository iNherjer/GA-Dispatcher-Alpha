#!/usr/bin/env node
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const { createRequire } = require('node:module');
const root = path.resolve(__dirname, '..');
const workspace = process.env.GA_EFB_VECTOR_BUILD_ROOT || path.join(__dirname, 'efb-vector-build');
const buildRequire = createRequire(path.join(workspace, 'package.json'));
const trackerRequire = createRequire(path.join(root, 'ga-tracker-client/package.json'));
const outputRoot = path.join(root, 'ga-tracker-client/efb-web-assets/vendor');
(async () => {
  const result = await buildRequire('esbuild').build({
    entryPoints: [path.join(root, 'ga-tracker-client/efb-vector-source/renderer.js')],
    nodePaths: [path.join(workspace, 'node_modules')],
    bundle: true, write: false, metafile: true, platform: 'browser', format: 'iife',
    globalName: 'GAEfbVectorRenderer', target: 'es2017', legalComments: 'eof'
  });
  const compiled = trackerRequire('@babel/core').transformSync(result.outputFiles[0].text, {
    babelrc: false, configFile: false, sourceType: 'script', comments: true, compact: true,
    presets: [[trackerRequire.resolve('@babel/preset-env'), { targets: { chrome: '49' }, modules: false,
      useBuiltIns: false, include: ['@babel/plugin-transform-spread', '@babel/plugin-transform-parameters'] }]]
  });
  fs.mkdirSync(outputRoot, { recursive: true });
  fs.writeFileSync(path.join(outputRoot, 'efb-vector-renderer.js'),
    '// Generated by tools/build-efb-vector-basemaps.cjs; Canvas 2D, Chrome 49 target.\n' + compiled.code + '\n');
  const packages = new Map();
  for (const file of Object.keys(result.metafile.inputs)) {
    let directory = path.dirname(path.resolve(file));
    while (directory !== path.dirname(directory)) {
      if (fs.existsSync(path.join(directory, 'package.json'))) {
        const pkg = JSON.parse(fs.readFileSync(path.join(directory, 'package.json'), 'utf8'));
        if (pkg.name && pkg.version && !packages.has(pkg.name)) {
          const texts = fs.readdirSync(directory).filter(name => /^licen[cs]e(?:\.|$)/i.test(name))
            .map(name => fs.readFileSync(path.join(directory, name), 'utf8')).join('\n');
          packages.set(pkg.name, `${pkg.name} ${pkg.version} (${pkg.license || 'see source'})\n${texts}`);
        }
        break;
      }
      directory = path.dirname(directory);
    }
  }
  fs.writeFileSync(path.join(outputRoot, 'efb-vector-LICENSES.txt'), [...packages.values()].join('\n\n---\n\n') + '\n');
  console.log('EFB_VECTOR_RENDERER_BUILT', fs.statSync(path.join(outputRoot, 'efb-vector-renderer.js')).size, 'bytes');
})().catch(error => { console.error(error.message); process.exitCode = 1; });
