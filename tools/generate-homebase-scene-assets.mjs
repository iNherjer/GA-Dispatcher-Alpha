// Pack catalogue is authoritative for mission eligibility and exact SimObject titles.
import fs from 'node:fs';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
export function buildSceneAssets(catalog){
 const features={},roles={};
 for(const asset of catalog.assets||[]){
  if(asset.missionSpawnable!==true||!asset.missionRoles?.includes('scene-prop'))continue;
  if(typeof asset.key!=='string'||!asset.key||typeof asset.title!=='string'||!asset.title)throw Error('Scene asset lacks identity/title');
  const feature='homebase_'+asset.key.toLowerCase().replace(/[^a-z0-9_]/g,'_'),role='homebase.scene.'+asset.key;
  if(features[feature])throw Error('Duplicate scene feature: '+feature);
  features[feature]={label:asset.label||asset.key,roles:[role],missionTags:[...(asset.missionTags||[])],assetKey:asset.key};
  roles[role]=[asset.title];
 }
 return {packageVersion:catalog.package?.version||'',features,roles};
}
const root=fileURLToPath(new URL('../',import.meta.url));
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 const result=buildSceneAssets(JSON.parse(fs.readFileSync(path.join(root,'homebase/assets/catalog.json'),'utf8')));
 fs.writeFileSync(path.join(root,'data/mission-homebase-scene-assets.js'),`// Generated by tools/generate-homebase-scene-assets.mjs; edit the pack catalogue instead.\n(function(root){\n'use strict';\nconst pack=${JSON.stringify(result,null,2)};\nconst catalog=root.MISSION_SCENE_ASSETS;\nif(!catalog)throw Error('Mission scene catalogue must load before Homebase scene assets');\nObject.assign(catalog.targetSceneFeatures,pack.features);\nObject.assign(catalog.roles,pack.roles);\ncatalog.homebaseScenePackageVersion=pack.packageVersion;\n})(window);\n`);
 console.log('Generated '+Object.keys(result.features).length+' scene-prop features from pack '+result.packageVersion);
}
