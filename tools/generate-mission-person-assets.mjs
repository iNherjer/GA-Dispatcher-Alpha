// Verbindet den Pack-Katalog (eigene Figuren mit person-Block) mit den Standardfiguren
// zu einer Personenliste für die Missions-Figurwahl.
// Ausgabe: data/mission-person-assets.js (global MISSION_PERSON_ASSETS, auch per require).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { checkAppearance, isPersonAsset, PERSON_ROLES } from './homebase-person-rules.mjs';

const FIELDS = ['look', 'ageBand', 'season', 'props', 'uses', 'description'];
const pickAppearance = (source) => Object.fromEntries(FIELDS.map((field) => [field, source[field]]));

export function buildPersonAssets(catalog, profiles, vocabulary) {
  const warnings = [];
  const figures = [];
  const fallbacks = profiles.packFallbacks || {};
  for (const asset of (catalog.assets || []).filter(isPersonAsset)) {
    const roles = asset.missionRoles || [];
    if (asset.missionSpawnable !== true || !roles.some((role) => PERSON_ROLES.has(role)) || !asset.person) continue;
    const person = asset.person;
    let appearance = person.appearance;
    let appearanceSource = 'catalog';
    if (!appearance && fallbacks[asset.key]) { appearance = fallbacks[asset.key]; appearanceSource = 'profile-fallback'; }
    if (!appearance) { warnings.push(`Pack-Figur ohne Aussehen: ${asset.key}`); continue; }
    const check = checkAppearance(appearance, vocabulary, asset.key);
    if (check.errors.length) { warnings.push(...check.errors); continue; }
    if (person.appearance && fallbacks[asset.key]) warnings.push(`packFallbacks.${asset.key} ist überflüssig (Katalog liefert appearance)`);
    figures.push({
      title: asset.title,
      key: asset.key,
      source: 'pack',
      appearanceSource,
      gender: person.gender,
      ...pickAppearance(appearance),
      maxWalkKts: Number(person.locomotion?.maxWalkKts) || 3,
      heightM: Number(person.heightM) || null,
      footprintRadiusM: Number(person.footprintRadiusM) || null
    });
  }
  for (const stock of profiles.stock || []) {
    const check = checkAppearance({ description: stock.title, ...stock }, vocabulary, stock.title);
    if (check.errors.length) { warnings.push(...check.errors); continue; }
    figures.push({
      title: stock.title,
      key: '',
      source: 'stock',
      appearanceSource: 'profile',
      gender: stock.gender,
      ...pickAppearance({ description: '', ...stock }),
      maxWalkKts: 5,
      heightM: null,
      footprintRadiusM: null
    });
  }
  for (const look of Object.keys(vocabulary.looks)) {
    for (const gender of ['female', 'male']) {
      if (!figures.some((figure) => figure.source === 'pack' && figure.look === look && figure.gender === gender)) {
        warnings.push(`Look ${look}/${gender}: nur Standardfiguren`);
      }
    }
  }
  return {
    result: { schema: 'mission-person-assets.v1', packageVersion: catalog.package?.version || '', vocabulary: vocabulary.schema,
      looks: vocabulary.looks, ageBands: vocabulary.ageBands, figures },
    warnings
  };
}

const root = fileURLToPath(new URL('../', import.meta.url));
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const read = (file) => JSON.parse(fs.readFileSync(path.join(root, file), 'utf8'));
  const { result, warnings } = buildPersonAssets(read('homebase/assets/catalog.json'), read('data/mission-person-asset-profiles.json'), read('data/mission-person-vocabulary.json'));
  fs.writeFileSync(path.join(root, 'data/mission-person-assets.js'),
    `// Generated by tools/generate-mission-person-assets.mjs; edit data/mission-person-asset-profiles.json or the pack catalogue instead.\n`
    + `(function(root){\n'use strict';\nconst assets=${JSON.stringify(result, null, 2)};\n`
    + `root.MISSION_PERSON_ASSETS=assets;\nif(typeof module!=='undefined'&&module.exports)module.exports=assets;\n`
    + `})(typeof window!=='undefined'?window:globalThis);\n`);
  warnings.filter((w) => !w.startsWith('Look ')).forEach((w) => console.warn('WARN ' + w));
  const pack = result.figures.filter((f) => f.source === 'pack').length;
  console.log(`Generated ${result.figures.length} person figures (${pack} pack, ${result.figures.length - pack} stock) from pack ${result.packageVersion}`);
}
