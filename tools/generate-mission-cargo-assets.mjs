// Joins the Homebase pack catalogue (identity, titles) with cargo appearance profiles (form, size, load).
// Pack assets with mission role "cargo" but no profile are reported and stay out of the selection.
import fs from 'node:fs';
import {fileURLToPath} from 'node:url';
import path from 'node:path';

const SIZES = ['s', 'm', 'l'];

export function buildCargoAssets(catalog, profiles) {
  const forms = {};
  const warnings = [];
  const addVariant = (variant) => {
    const formDef = profiles.forms?.[variant.form];
    if (!formDef?.label) throw Error('Unknown cargo form: ' + variant.form);
    if (!SIZES.includes(variant.size)) throw Error('Invalid cargo size for ' + variant.title);
    const [min, max] = Array.isArray(variant.loadLbs) ? variant.loadLbs.map(Number) : [];
    if (!(min > 0 && max >= min)) throw Error('Invalid load range for ' + variant.title);
    const uses = [...new Set((variant.uses || []).map(String))];
    if (!uses.length) throw Error('Cargo profile without uses: ' + variant.title);
    const form = (forms[variant.form] ||= { id: variant.form, label: formDef.label, tags: [], variants: [] });
    form.variants.push({ key: variant.key || null, title: variant.title, label: variant.label || variant.title, size: variant.size, loadLbs: [min, max], uses });
    form.tags = [...new Set([...form.tags, ...(variant.tags || [])])];
  };
  const cargoAssets = (catalog.assets || []).filter(asset => asset.missionSpawnable === true && asset.missionRoles?.includes('cargo'));
  for (const asset of cargoAssets) {
    const profile = profiles.assets?.[asset.key];
    if (!profile) { warnings.push('Cargo asset without profile: ' + asset.key); continue; }
    addVariant({ ...profile, key: asset.key, title: asset.title, label: asset.label, tags: (asset.missionTags || []).filter(tag => tag !== 'cargo') });
  }
  for (const key of Object.keys(profiles.assets || {})) {
    if (!cargoAssets.some(asset => asset.key === key)) warnings.push('Profile without spawnable cargo asset: ' + key);
  }
  for (const stock of profiles.stock || []) addVariant({ ...stock, tags: [] });
  for (const form of Object.values(forms)) form.variants.sort((a, b) => a.loadLbs[0] - b.loadLbs[0] || a.title.localeCompare(b.title));
  return { schema: 'mission-cargo-assets.v1', packageVersion: catalog.package?.version || '', forms, warnings };
}

const root = fileURLToPath(new URL('../', import.meta.url));
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const catalog = JSON.parse(fs.readFileSync(path.join(root, 'homebase/assets/catalog.json'), 'utf8'));
  const profiles = JSON.parse(fs.readFileSync(path.join(root, 'data/mission-cargo-asset-profiles.json'), 'utf8'));
  const { warnings, ...result } = buildCargoAssets(catalog, profiles);
  fs.writeFileSync(path.join(root, 'data/mission-cargo-assets.js'),
    `// Generated by tools/generate-mission-cargo-assets.mjs; edit data/mission-cargo-asset-profiles.json or the pack catalogue instead.\n`
    + `(function(root){\n'use strict';\nconst assets=${JSON.stringify(result, null, 2)};\n`
    + `root.MISSION_CARGO_ASSETS=assets;\nif(typeof module!=='undefined'&&module.exports)module.exports=assets;\n`
    + `})(typeof window!=='undefined'?window:globalThis);\n`);
  warnings.forEach(w => console.warn('WARN ' + w));
  console.log('Generated ' + Object.keys(result.forms).length + ' cargo forms with '
    + Object.values(result.forms).reduce((n, f) => n + f.variants.length, 0) + ' variants from pack ' + result.packageVersion);
}
